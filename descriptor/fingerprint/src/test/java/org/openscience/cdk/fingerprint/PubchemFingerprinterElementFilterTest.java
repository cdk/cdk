    private static String hex(byte[] bytes) {
        StringBuilder sb = new StringBuilder();
        for (byte b : bytes)
            sb.append(String.format("%02x", b));
        return sb.toString();
    }

    @Test
    void sameFingerprintsAsBeforeTheElementFilter() throws Exception {
        SmilesParser smipar = new SmilesParser(SilentChemObjectBuilder.getInstance());
        CDKHydrogenAdder adder = CDKHydrogenAdder.getInstance(SilentChemObjectBuilder.getInstance());
        // one fingerprinter for all, the SMARTS cache is reused between molecules
        PubchemFingerprinter fpr = new PubchemFingerprinter(SilentChemObjectBuilder.getInstance());
        for (String[] entry : GOLDEN) {
            IAtomContainer mol = smipar.parseSmiles(entry[0]);
            AtomContainerManipulator.percieveAtomTypesAndConfigureAtoms(mol);
            adder.addImplicitHydrogens(mol);
            Aromaticity.cdkLegacy().apply(mol);
            fpr.getBitFingerprint(mol);
            Assertions.assertEquals(entry[1], hex(fpr.getFingerprintAsBytes()), entry[0]);
        }
    }
